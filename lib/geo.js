export function classifyIntl(text) {
  if (!text) return null
  const lower = ` ${text.toLowerCase()} `
  for (const [region, keywords] of Object.entries(INTL_REGION_KEYWORDS)) {
    if (keywords.some(k => lower.includes(k))) return region
  }
  return null
}
